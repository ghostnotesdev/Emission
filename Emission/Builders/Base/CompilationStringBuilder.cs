using Microsoft.CodeAnalysis;
using System.Text;

namespace Emission.Builders;
public class CompilationStringBuilder(ushort indentDepth = 0) : ICompilationStringBuilder
{
    private readonly StringBuilder _sb = new();
    private bool isStartOfLine = true;
    private ushort _indentDepth = indentDepth;
    private string _indent = new('\t', indentDepth);

    public bool IsStartOfLine => isStartOfLine;

    public ushort IndentDepth
    {
        get => _indentDepth;
        set
        {
            _indentDepth = value;
            _indent = new('\t', value);
        }
    }

    public char? GetLastChar()
    {
        if (_sb.Length == 0 || isStartOfLine)
            return null;

        return _sb[_sb.Length - 1];
    }

    public ICompilationStringBuilder AppendLine()
    {
        _sb.AppendLine();
        isStartOfLine = true;
        return this;
    }

    public ICompilationStringBuilder AppendLine(string value)
    {
        AppendIndentIfStartOfLine();
        _sb.AppendLine(value);
        isStartOfLine = true;
        return this;
    }

    public ICompilationStringBuilder Append(string value)
    {
        AppendIndentIfStartOfLine();
        _sb.Append(value);
        isStartOfLine = false;
        return this;
    }

    public ICompilationStringBuilder IncreaseIndent()
    {
        IndentDepth++;
        return this;
    }

    public ICompilationStringBuilder DecreaseIndent()
    {
        if (IndentDepth == 0)
            return this;

        IndentDepth--;
        return this;
    }

    public ICompilationStringBuilder EnsureSpace()
    {
        if (isStartOfLine)
            return this;

        if (GetLastChar() != ' ')
            return Append(" ");

        return this;
    }

    public ICompilationStringBuilder EnsureSemicolon()
    {
        if (isStartOfLine)
            return this;

        if (GetLastChar() != ';')
            return Append(";");

        return this;
    }

    public ICompilationStringBuilder EnsureNewLine()
    {
        if (isStartOfLine)
            return this;

        return AppendLine();
    }

    public virtual ICompilationStringBuilder AppendGeneratorHeader(string _namespace)
    {
        AppendLine("// ------------------------------------------------------------------------------");
        AppendLine("// <auto-generated>");
        AppendLine("//     This code was generated by a tool.");
        AppendLine("//");
        AppendLine("//     Changes to this file may cause incorrect behavior and will be lost if");
        AppendLine("//     the code is regenerated.");
        AppendLine("// </auto-generated>");
        AppendLine("// ------------------------------------------------------------------------------");
        AppendLine();
        AppendLine($"namespace {_namespace};");
        AppendLine();
        return this;
    }

    public ICompilationStringBuilder AppendLinesWithSeparator(string separator, IEnumerable<string> lines) =>
        AppendLinesWithSeparator(separator, lines.Select(line => new StatementBuilder().UseStatement(line)));

    public ICompilationStringBuilder AppendLinesWithSeparator(string separator, params IStatementBuilder[] valueBuilders)
        => AppendLinesWithSeparator(separator, (IEnumerable<IStatementBuilder>)valueBuilders);

    public ICompilationStringBuilder AppendLinesWithSeparator(string separator, IEnumerable<IStatementBuilder> valueBuilders)
    {
        bool first = true;

        foreach (var builder in valueBuilders)
        {
            if (!first)
                AppendLine(separator);

            builder.Build(this);
            first = false;
        }

        if (!first)
            AppendLine();

        return this;
    }

    public ICompilationStringBuilder AppendWithSeparator(string separator, IEnumerable<string> content) =>
        AppendWithSeparator(separator, content.Select(c => new StatementBuilder().UseStatement(c)));

    public ICompilationStringBuilder AppendWithSeparator(string separator, params IStatementBuilder[] valueBuilders)
        => AppendWithSeparator(separator, (IEnumerable<IStatementBuilder>)valueBuilders);

    public ICompilationStringBuilder AppendWithSeparator(string separator, IEnumerable<IStatementBuilder> valueBuilders)
    {
        bool first = true;

        foreach (var builder in valueBuilders)
        {
            if (!first)
                Append(separator);

            builder.Build(this);

            first = false;
        }

        return this;
    }

    private void AppendIndentIfStartOfLine()
    {
        if (isStartOfLine)
        {
            _sb.Append(_indent);
            isStartOfLine = false;
        }
    }

    public override string ToString() => _sb.ToString();
}
